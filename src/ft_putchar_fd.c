#include <unistd.h>

/**
 * @brief Writes one character to a file descriptor.
 *
 * @param c Character to write.
 * @param fd Destination file descriptor.
 */
void	ft_putchar_fd(char c, int fd)
{
	write(fd, &c, 1);
}
