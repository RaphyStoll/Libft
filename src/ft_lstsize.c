#include "../includes/types.h"

/**
 * @brief Counts the number of nodes in a linked list.
 *
 * @param lst Head of the list.
 * @return Number of nodes.
 */
int	ft_lstsize(t_list *lst)
{
	int	count;

	count = 0;
	while (lst)
	{
		lst = lst->next;
		count++;
	}
	return (count);
}
